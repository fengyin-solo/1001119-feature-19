def attach_to_materials(materials: list[dict[str, Any]]) -> None:
    """把授权结论台账挂到对应材料上，并把预占数量反映到库存。

    台账只记录授权口径与结论，刻意不写供应商，越权拒绝也不暴露供应商。
    """
    # 材料编号 -> 台账条目
    ledgers: dict[str, list[dict[str, Any]]] = {}
    tables = build_authorization_tables()
    for req in tables["material_requisition"]:
        code = str(req.get("材料编号", ""))
        ledgers.setdefault(code, []).append({
            "领用单号": req["领用单号"],
            "工程编号": req["工程编号"],
            "施工路段": req["施工路段"],
            "材料类别": req["材料类别"],
            "领用单位": req["领用单位"],
            "数量": req["申请数量"],
            "授权结论": req["授权结论"],
            "授权依据": req["授权依据"],
            "状态": req["状态"],
            "时间": req["申请时间"],
        })

    for row in materials:
        code = str(row.get("材料编号", ""))
        row["授权结论台账"] = ledgers.get(code, [])
        # 与领用单口径保持一致：MATE-0001 有一单 15 吨处于预占待发
        if code == "MATE-0001":
            row["预占数量"] = 15


# 启动时只构造一次，供 Store 深拷贝，避免不同 Store 实例共享引用。
_AUTHORIZATION_TABLES = build_authorization_tables()


def bootstrap(seed_rows: dict[str, list[dict[str, Any]]]) -> None:
    """把授权柜表与材料台账并入内存仓库（原地扩展 SEED_ROWS 的副本）。"""
    for name, rows in _AUTHORIZATION_TABLES.items():
        seed_rows[name] = deepcopy(rows)
    attach_to_materials(seed_rows["material"])
